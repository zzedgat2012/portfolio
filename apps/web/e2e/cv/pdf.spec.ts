import { expect, test } from '../fixtures';

const PDF_PATH = '/edgar-ferreira-cv.pdf';

test.describe('[story 2.5] CV PDF', () => {
  test('is generated by the build and served as application/pdf @smoke', async ({ request }) => {
    const response = await request.get(PDF_PATH);

    expect(response.status()).toBe(200);
    expect(response.headers()['content-type']).toContain('application/pdf');
    const body = await response.body();
    expect(body.subarray(0, 5).toString('latin1')).toBe('%PDF-');
  });

  // Chromium writes A4 as a 595.28 x 841.89 pt MediaBox (rounded to 594.96 x 841.92).
  test('uses A4 pages', async ({ request }) => {
    const body = (await (await request.get(PDF_PATH)).body()).toString('latin1');

    const mediaBoxes = [...body.matchAll(/\/MediaBox\s*\[\s*0 0 ([\d.]+) ([\d.]+)\s*\]/g)];
    expect(mediaBoxes.length).toBeGreaterThan(0);
    for (const [, width = '0', height = '0'] of mediaBoxes) {
      expect(Number(width)).toBeCloseTo(595.28, 0);
      expect(Number(height)).toBeCloseTo(841.89, 0);
    }
  });
});

test.describe('[story 2.5] Home "Download CV" link', () => {
  test('downloads the PDF as edgar-ferreira-cv.pdf @smoke', async ({ page, homePage }) => {
    await homePage.open();
    const link = homePage.experience.getByRole('link', { name: 'Download CV' });

    await expect(link).toHaveAttribute('href', PDF_PATH);
    await expect(link).toHaveAttribute('download', 'edgar-ferreira-cv.pdf');

    const downloadPromise = page.waitForEvent('download');
    await link.click();
    const download = await downloadPromise;
    expect(download.suggestedFilename()).toBe('edgar-ferreira-cv.pdf');
  });
});
